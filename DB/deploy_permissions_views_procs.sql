-- View hồ sơ học viên theo USER
create or replace view v_thongtin_canhan_hv as
   select hv.ho_ten,
          hv.ma_hoc_vien,
          hv.gioi_tinh,
          hv.ngay_sinh,
          hv.so_dien_thoai,
          hv.dia_chi,
          tk.email,
          tk.ten_dang_nhap
     from hoc_vien hv
     join tai_khoan tk
   on tk.id_nguoi_dung = hv.id_hoc_vien
    where upper(tk.ten_dang_nhap) = user;

-- Quyền cập nhật số điện thoại và địa chỉ trên view hồ sơ
-- Lưu ý: cần INSTEAD OF trigger nếu Oracle không cho UPDATE trực tiếp view này
-- Ở đây giả sử hai cột map thẳng xuống HOC_VIEN, dùng trigger để chuyển UPDATE vào bảng gốc
create or replace trigger trg_v_tt_canhan_update instead of
   update of so_dien_thoai,dia_chi on v_thongtin_canhan_hv
   for each row
begin
   update hoc_vien hv
      set hv.so_dien_thoai = :new.so_dien_thoai,
          hv.dia_chi = :new.dia_chi
    where hv.id_hoc_vien = (
      select tk.id_nguoi_dung
        from tai_khoan tk
       where upper(tk.ten_dang_nhap) = user
   );
end;
/

grant select on v_thongtin_canhan_hv to public;
grant update ( so_dien_thoai,
               dia_chi ) on v_thongtin_canhan_hv to public;

