-- Thủ tục học viên gửi yêu cầu đăng ký khóa học
create or replace procedure sp_gui_yeu_cau_dang_ky_khoa (
   p_course_code in varchar2,
   p_ket_qua     out nvarchar2
) as
   v_user_id     number;
   v_hoc_vien_id number;
   v_khoa_id     number;
begin
   if p_course_code is null then
      p_ket_qua := N'Mã khóa học không hợp lệ';
      return;
   end if;
   select id_nguoi_dung
     into v_user_id
     from tai_khoan
    where upper(ten_dang_nhap) = user;
   select id_hoc_vien
     into v_hoc_vien_id
     from hoc_vien
    where id_hoc_vien = v_user_id;
   select id_khoa_hoc
     into v_khoa_id
     from khoa_hoc
    where ma_khoa_hoc = p_course_code;

    -- Tạo bản ghi đơn đăng ký ở trạng thái Chờ duyệt, gán lớp đang tuyển sinh (nếu có)
    -- Tùy bạn có muốn tạo bảng YEU_CAU_DANG_KY hay tạo trực tiếp DON_DANG_KY với lớp đang mở.
   insert into don_dang_ky (
      ma_dang_ky,
      ngay_dang_ky,
      trang_thai,
      id_hoc_vien,
      id_lop_hoc
   ) values ( 'DGK_'
              || to_char(
      sysdate,
      'YYYYMMDDHH24MISS'
   )
              || '_'
              || dbms_random.value(
      1000,
      9999
   ),
              sysdate,
              N'Chờ duyệt',
              v_hoc_vien_id,
              (
                 select id_lop_hoc
                   from lop_hoc
                                    where id_khoa_hoc = v_khoa_id
                                        and trang_thai = N'Đang tuyển sinh'
                  fetch first 1 rows only
              ) );

   p_ket_qua := N'Gửi yêu cầu thành công';
exception
   when no_data_found then
      p_ket_qua := N'Không tìm thấy học viên/lớp/khóa học phù hợp';
   when others then
      p_ket_qua := N'Lỗi: ' || sqlerrm;
end;
/

