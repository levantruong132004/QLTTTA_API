       lh.ngay_ket_thuc,
       dk.id_hoc_vien,
       dk.id_lop_hoc
  from don_dang_ky dk
  join lop_hoc lh on dk.id_lop_hoc = lh.id_lop_hoc
  join khoa_hoc kh on lh.id_khoa_hoc = kh.id_khoa_hoc
 where dk.id_hoc_vien = (select id_nguoi_dung from v_current_user_id);
/
grant select on v_dang_ky_cua_toi to role_hocvien;

