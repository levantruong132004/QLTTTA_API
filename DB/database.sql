-- Bảng 1: VAI_TRO
create table vai_tro (
   id_vai_tro  number(10) generated by default on null as identity primary key,
   ten_vai_tro nvarchar2(50) not null unique
);
comment on table vai_tro is
   'Lưu trữ các vai trò người dùng (HocVien, KeToan, NhanVienHocVu...)';

-- Bảng 2: TAI_KHOAN
create table tai_khoan (
   id_nguoi_dung        number(10) generated by default on null as identity primary key,
   ten_dang_nhap        varchar2(50) not null unique,
   mat_khau             varchar2(256) not null,
   email                varchar2(100) not null unique,
   id_vai_tro           number(10) not null,
   trang_thai_kich_hoat number(1) default 1 not null,
   session_id_pc        varchar2(64),
   session_id_mobile    varchar2(64),
   constraint fk_taikhoan_vaitro foreign key ( id_vai_tro )
      references vai_tro ( id_vai_tro )
);
comment on table tai_khoan is
   'Bảng cơ sở chứa thông tin đăng nhập chung của các tác nhân';
-- Bảng 3: HOC_VIEN
create table hoc_vien (
   id_hoc_vien   number(10) primary key,
   ho_ten        nvarchar2(100) not null,
   ma_hoc_vien   varchar2(20) unique,
   gioi_tinh     nvarchar2(10) not null,
   ngay_sinh     date,
   so_dien_thoai varchar2(15),
   dia_chi       nvarchar2(255),
   constraint fk_hocvien_taikhoan foreign key ( id_hoc_vien )
      references tai_khoan ( id_nguoi_dung )
         on delete cascade
);
comment on table hoc_vien is
   'Lưu thông tin chi tiết của học viên';

