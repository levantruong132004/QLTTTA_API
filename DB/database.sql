-- Bảng 8: LOP_HOC
create table lop_hoc (
   id_lop_hoc    number(10) generated by default on null as identity primary key,
   ma_lop_hoc    varchar2(30) unique,
   ten_lop_hoc   nvarchar2(200) not null,
   ngay_bat_dau  date not null,
   ngay_ket_thuc date not null,
   si_so_toi_da  number(3) not null,
   trang_thai    nvarchar2(30) default N'Đang tuyển sinh' check ( trang_thai in ( N'Đang tuyển sinh',
                                                                               N'Đã bắt đầu',
                                                                               N'Đã hủy',
                                                                               N'Đã kết thúc' ) ),
   id_khoa_hoc   number(10) not null,
   id_giang_vien number(10),
   constraint fk_lophoc_khoahoc foreign key ( id_khoa_hoc )
      references khoa_hoc ( id_khoa_hoc ),
   constraint fk_lophoc_giangvien foreign key ( id_giang_vien )
      references giang_vien ( id_giang_vien )
);
comment on table lop_hoc is
   'Quản lý các lớp học cụ thể được mở từ một khóa học';

-- Bảng 9: LICH_HOC
create table lich_hoc (
   id_lich_hoc    number(10) generated by default on null as identity primary key,
   id_lop_hoc     number(10) not null,
   thu_trong_tuan number(1) not null, -- 2=Thứ Hai, 3=Thứ Ba... 8=Chủ Nhật
   gio_bat_dau    varchar2(5) not null, -- Định dạng HH24:MI
   gio_ket_thuc   varchar2(5) not null, -- Định dạng HH24:MI
   constraint fk_lichhoc_lophoc foreign key ( id_lop_hoc )
      references lop_hoc ( id_lop_hoc )
         on delete cascade,
   constraint chk_thu_trong_tuan check ( thu_trong_tuan between 2 and 8 )
);
comment on table lich_hoc is
   'Lưu lịch học cố định trong tuần của một lớp';

-- Bảng 10: DON_DANG_KY
create table don_dang_ky (
   id_dang_ky         number(10) generated by default on null as identity primary key,
   ma_dang_ky         varchar2(20) not null unique,
   ngay_dang_ky       date default sysdate not null,
   ngay_duyet         date,
   trang_thai         nvarchar2(30) default N'Chờ duyệt' check ( trang_thai in ( N'Chờ duyệt',
                                                                         N'Đã duyệt',
                                                                         N'Đã từ chối',
                                                                         N'Đã lập hóa đơn',
                                                                         N'Đã nhập học' ) ),
   diem_cuoi_khoa     number(5,2),
   id_hoc_vien        number(10) not null,
   id_lop_hoc         number(10) not null,
   id_nhan_vien_duyet number(10),
   constraint fk_dangky_hocvien foreign key ( id_hoc_vien )
      references hoc_vien ( id_hoc_vien ),
   constraint fk_dangky_lophoc foreign key ( id_lop_hoc )
      references lop_hoc ( id_lop_hoc ),
   constraint fk_dangky_nvhocvu foreign key ( id_nhan_vien_duyet )
      references nhan_vien_hoc_vu ( id_nhan_vien ),
   constraint uk_hocvien_lophoc unique ( id_hoc_vien,
                                         id_lop_hoc )
);
comment on table don_dang_ky is
   'Ghi nhận việc một học viên đăng ký vào một lớp học';

