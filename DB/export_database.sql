  CREATE OR REPLACE EDITIONABLE PROCEDURE "QLTT_ADMIN"."SP_KILL_USER_SESSION" (
    p_username IN VARCHAR2
) AS
    TYPE t_session_rec IS RECORD (sid NUMBER, serial# NUMBER, status VARCHAR2(20));
    TYPE t_session_cur IS REF CURSOR;
    v_cur t_session_cur;
    v_rec t_session_rec;
    v_sql VARCHAR2(1000);
    v_kill_sql VARCHAR2(1000);
    v_count NUMBER := 0;
BEGIN
    IF p_username IS NULL OR LENGTH(TRIM(p_username)) = 0 THEN
        RETURN;
    END IF;

    -- Find sessions (Active or Inactive)
    v_sql := 'SELECT sid, serial#, status FROM v$session WHERE UPPER(username) = UPPER(TRIM(:1))';

    OPEN v_cur FOR v_sql USING p_username;
    LOOP
        FETCH v_cur INTO v_rec;
        EXIT WHEN v_cur%NOTFOUND;

        v_count := v_count + 1;

        -- Try DISCONNECT SESSION first (removes from v$session immediately for dedicated server)
        BEGIN
            v_kill_sql := 'ALTER SYSTEM DISCONNECT SESSION ''' || v_rec.sid || ',' || v_rec.serial# || ''' IMMEDIATE';
            EXECUTE IMMEDIATE v_kill_sql;
        EXCEPTION WHEN OTHERS THEN
            -- Fallback to KILL SESSION (marks as KILLED)
            BEGIN
                v_kill_sql := 'ALTER SYSTEM KILL SESSION ''' || v_rec.sid || ',' || v_rec.serial# || ''' IMMEDIATE';
                EXECUTE IMMEDIATE v_kill_sql;
            EXCEPTION WHEN OTHERS THEN
                NULL; -- Ignore if already gone
            END;
        END;
    END LOOP;
    CLOSE v_cur;

    -- If we found sessions but failed to kill (and didn't raise error above), we might want to know.
    -- But for now, we assume if EXECUTE IMMEDIATE didn't raise, it worked.
EXCEPTION WHEN OTHERS THEN
    IF v_cur%ISOPEN THEN CLOSE v_cur; END IF;
    RAISE;
END;

/
