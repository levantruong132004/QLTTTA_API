  CREATE OR REPLACE EDITIONABLE FUNCTION "QLTT_ADMIN"."SIMPLE_HASH" (p_text IN VARCHAR2)
RETURN VARCHAR2
AS
    v_hash NUMBER := 0;
    v_char CHAR(1);
BEGIN
    FOR i IN 1 .. LENGTH(p_text) LOOP
        v_char := SUBSTR(p_text, i, 1);
        v_hash := MOD((v_hash * 131) + ASCII(v_char), 999999999);
    END LOOP;

    RETURN TO_CHAR(v_hash);
END;

