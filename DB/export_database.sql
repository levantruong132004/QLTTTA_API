set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "QLTT_ADMIN"."SP_XOA_HOC_VIEN" (
    p_id_hoc_vien IN NUMBER,
    p_ket_qua     OUT NVARCHAR2
)
AS
    v_username_app   VARCHAR2(50);    -- tên trong TAI_KHOAN
    v_username_real  VARCHAR2(128);   -- tên đúng trong ALL_USERS
    v_count_dk       NUMBER;
BEGIN
    -------------------------------------------------------------------
    -- 1. Lấy username trong ứng dụng
    -------------------------------------------------------------------
    BEGIN
        SELECT tk.TEN_DANG_NHAP
        INTO v_username_app
        FROM HOC_VIEN hv
        JOIN TAI_KHOAN tk ON hv.ID_HOC_VIEN = tk.ID_NGUOI_DUNG
        WHERE hv.ID_HOC_VIEN = p_id_hoc_vien;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            p_ket_qua := u'H\1ecdc vi\00ean kh\00f4ng t\1ed3n t\1ea1i.';
            RETURN;
    END;

    -------------------------------------------------------------------
    -- 2. Kiểm tra đơn đăng ký
    -------------------------------------------------------------------
    SELECT COUNT(*) INTO v_count_dk
    FROM DON_DANG_KY
    WHERE ID_HOC_VIEN = p_id_hoc_vien;

    IF v_count_dk > 0 THEN
        p_ket_qua := u'Kh\00f4ng th\1ec3 x\00f3a: H\1ecdc vi\00ean \0111\00e3 c\00f3 \0111\01a1n \0111\0103ng k\00fd.';
        RETURN;
    END IF;

    -------------------------------------------------------------------
    -- 3. Lấy username thật trong Oracle
    -------------------------------------------------------------------
    BEGIN
        SELECT USERNAME
        INTO v_username_real
        FROM ALL_USERS
        WHERE USERNAME = v_username_app
           OR USERNAME = UPPER(v_username_app)
           OR USERNAME = LOWER(v_username_app);

    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            -- User Oracle không tồn tại → bỏ qua
            v_username_real := NULL;
    END;

    -------------------------------------------------------------------
    -- 4. Nếu user tồn tại → DROP USER chính xác
    -------------------------------------------------------------------
    IF v_username_real IS NOT NULL THEN
        BEGIN
            EXECUTE IMMEDIATE 'DROP USER "' || v_username_real || '" CASCADE';
        EXCEPTION
            WHEN OTHERS THEN
                NULL;
        END;
    END IF;

    -------------------------------------------------------------------
    -- 5. Xóa tài khoản hệ thống
    -------------------------------------------------------------------
    DELETE FROM TAI_KHOAN WHERE ID_NGUOI_DUNG = p_id_hoc_vien;

    COMMIT;
    p_ket_qua := u'X\00f3a h\1ecdc vi\00ean th\00e0nh c\00f4ng!';
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        p_ket_qua := u'L\1ed7i: ' || SQLERRM;
END;

